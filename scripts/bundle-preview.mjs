/**
 * Bundles the built CSS + JS into a single, fully self-contained HTML file.
 *
 * Why: `index.html` is the production entry (external, cacheable assets), while
 * `preview.html` is one portable artifact: no sub-resources, no server, no CDN.
 * Safe to open from disk, email to a client, or drop into a review pane.
 *
 * Usage: node ./scripts/bundle-preview.mjs
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFile(resolve(root, p), 'utf8');

const [shell, css, js, favicon] = await Promise.all([
  read('index.html'),
  read('dist/app.css'),
  read('dist/app.js'),
  read('assets/favicon.svg'),
]);

/* Guard: a missing build would silently ship an empty preview. */
if (css.trim().length === 0 || js.trim().length === 0) {
  throw new Error(
    'bundle-preview: dist/app.css or dist/app.js is empty - run `npm run build` first.',
  );
}

const html = shell
  /* Function replacers are mandatory here: the compiled CSS/JS legitimately
     contains `$'`, `$&` and other dollar-patterns that a string replacement
     would silently reinterpret as match back-references, corrupting the bundle. */
  .replace(
    /\s*<link rel="stylesheet" href="\.\/dist\/app\.css(?:\?[^"]*)?" \/>/,
    () => `\n    <style>\n${css}\n    </style>`,
  )
  .replace(
    /\s*<script src="\.\/dist\/app\.js(?:\?[^"]*)?" defer><\/script>/,
    () => `\n    <script>\n${js}\n    </script>`,
  )
  /* Inline the favicon too, so the preview keeps zero external sub-resources. */
  .replace(
    /\.\/assets\/favicon\.svg/g,
    () => `data:image/svg+xml;base64,${Buffer.from(favicon).toString('base64')}`,
  )
  .replace(
    '<title>',
    '<!-- Self-contained build · generated by scripts/bundle-preview.mjs -->\n    <title>',
  );

if (html.includes('./dist/') || html.includes('./assets/')) {
  throw new Error('bundle-preview: an external sub-resource reference survived inlining.');
}

await writeFile(resolve(root, 'preview.html'), html, 'utf8');

const kb = (s) => `${(Buffer.byteLength(s) / 1024).toFixed(1)} KB`;
console.log(`preview.html written - ${kb(html)} (css ${kb(css)} + js ${kb(js)} inlined)`);
